"""Trusted operator CLI. Agents must not hold unrestricted Temporal namespace keys."""
import argparse
import asyncio
import json
from pathlib import Path
from .connection import connect, task_queue
from .contracts import validate_spec
from .workflow import DevelopmentWorkflow
from .runtime import DevelopmentTransport


async def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=["start", "status", "result", "approve", "cancel"])
    parser.add_argument("spec", help="Frozen spec generated by the trusted task registry")
    parser.add_argument("--receipt-id")
    parser.add_argument("--plan-sha256")
    parser.add_argument("--reason")
    args = parser.parse_args()
    spec = json.loads(Path(args.spec).read_text()); validate_spec(spec)
    client = await connect()
    runtime = DevelopmentTransport(client, task_queue())
    if args.action == "start":
        run_id = await runtime.start(spec)
        print(json.dumps({"workflow_id": "dev-task/" + spec["request"]["task_id"], "run_id": run_id}))
        return
    handle, description = await runtime.lookup(spec)
    if args.action == "status":
        print(json.dumps(await handle.query(DevelopmentWorkflow.status), ensure_ascii=False, indent=2))
    elif args.action == "result":
        print(json.dumps(await handle.result(follow_runs=False), ensure_ascii=False, indent=2))
    elif args.action == "approve":
        if not args.receipt_id or not args.plan_sha256: parser.error("approve requires --receipt-id and --plan-sha256")
        await handle.signal(DevelopmentWorkflow.approve_plan,
            {"request_sha256": spec["request_sha256"], "plan_sha256": args.plan_sha256, "receipt_id": args.receipt_id})
        print("Approval reference sent. Query status to confirm the trusted receipt was accepted.")
    else:
        if not args.reason: parser.error("cancel requires --reason")
        await runtime.cancel(spec, description.run_id, args.reason)
        print("Cancellation requested. External jobs remain unconfirmed until terminal receipts/fences are reconciled.")


if __name__ == "__main__": asyncio.run(main())
